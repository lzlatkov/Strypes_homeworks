x = int(input())
y = int(input())

if (-1 <= x <= 1 and -4 <= y <= 0) or (x**2 + y**2 <= 4 and y >= 0):
    print(f"Точката с координати {x}, {y} се намира вътре в защрихованата част на фигурата")
else:
    print(f"Точката с координати {x}, {y} не се намира вътре в защрихованата част на фигурата")